/**
 * Returns a randomized subset of vocabulary pairs for a matching game round
 * @param {'beginner' | 'intermediate' | 'advanced'} level 
 * @param {number} count Number of pairs (default 8)
 */
export function getRandomVocabPairs(level = 'beginner', count = 8) {
  const pool = VOCAB_DATA[level] || VOCAB_DATA.beginner;
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
